from __future__ import annotations
from pathlib import Path
from datetime import datetime
import json
import shlex


class TransferService:
    FORMAT = "initra-profile"
    VERSION = 1

    @classmethod
    def export_profile_json(cls, profile, destination):
        payload = {
            "format": cls.FORMAT,
            "version": cls.VERSION,
            "exported_at": datetime.now().isoformat(timespec="seconds"),
            "profile": {
                "name": profile.get("name", "Imported profile"),
                "description": profile.get("description", ""),
                "packages": list(profile.get("packages", [])),
                "services": list(profile.get("services", [])),
                "tweaks": dict(profile.get("tweaks", {})),
                "dotfiles": bool(profile.get("dotfiles", False)),
            },
        }
        Path(destination).write_text(
            json.dumps(payload, indent=2), encoding="utf-8"
        )
        return Path(destination)

    @classmethod
    def import_profile_json(cls, source):
        data = json.loads(Path(source).read_text(encoding="utf-8"))
        if data.get("format") != cls.FORMAT:
            raise ValueError("This is not an Initra profile export.")
        if int(data.get("version", 0)) > cls.VERSION:
            raise ValueError("This profile was created by a newer Initra export format.")
        profile = data.get("profile")
        if not isinstance(profile, dict):
            raise ValueError("Profile data is missing.")
        packages = profile.get("packages", [])
        services = profile.get("services", [])
        tweaks = profile.get("tweaks", {})
        if not isinstance(packages, list) or not isinstance(services, list) or not isinstance(tweaks, dict):
            raise ValueError("Profile structure is invalid.")
        return {
            "id": "",
            "name": str(profile.get("name", "Imported profile")).strip() or "Imported profile",
            "description": str(profile.get("description", "")),
            "packages": [str(x) for x in packages if str(x).strip()],
            "services": [str(x) for x in services if str(x).strip()],
            "tweaks": tweaks,
            "dotfiles": bool(profile.get("dotfiles", False)),
        }

    @staticmethod
    def shell_script(profile):
        packages = sorted(set(str(x) for x in profile.get("packages", []) if str(x).strip()))
        services = sorted(set(str(x) for x in profile.get("services", []) if str(x).strip()))
        tweaks = dict(profile.get("tweaks", {}))

        lines = [
            "#!/usr/bin/env bash",
            "set -euo pipefail",
            "",
            f"# Generated by Initra for profile: {profile.get('name', 'Profile')}",
            "# Review this script before running it.",
            "",
            'if ! command -v apt-get >/dev/null 2>&1; then',
            '  echo "This generated script currently targets APT-based distributions." >&2',
            "  exit 1",
            "fi",
            "",
        ]

        if packages:
            quoted = " ".join(shlex.quote(p) for p in packages)
            lines += [
                'echo "Updating package index..."',
                "sudo apt-get update",
                'echo "Installing selected packages..."',
                f"sudo apt-get install -y {quoted}",
                "",
            ]

        for service in services:
            safe = shlex.quote(service)
            lines += [
                f'echo "Enabling service: {service}"',
                f"sudo systemctl enable --now {safe}",
                "",
            ]

        mapping = {
            "animations": ("org.gnome.desktop.interface", "enable-animations"),
            "hot_corners": ("org.gnome.desktop.interface", "enable-hot-corners"),
        }
        for name, enabled in tweaks.items():
            if name not in mapping:
                continue
            schema, key = mapping[name]
            value = "true" if bool(enabled) else "false"
            lines += [
                f"if command -v gsettings >/dev/null 2>&1; then",
                f"  gsettings set {shlex.quote(schema)} {shlex.quote(key)} {value} || true",
                "fi",
                "",
            ]

        if profile.get("dotfiles"):
            lines += [
                "# Dotfiles were selected in this profile.",
                "# Initra does not export unknown/private dotfile contents into the script.",
                'echo "Dotfiles step selected: apply your reviewed dotfiles separately."',
                "",
            ]

        lines += ['echo "Initra setup script finished."', ""]
        return "\n".join(lines)


    @classmethod
    def shell_script_for_manager(cls, profile, manager="apt"):
        packages = sorted(set(str(x) for x in profile.get("packages", []) if str(x).strip()))
        quoted = " ".join(shlex.quote(p) for p in packages)
        lines = ["#!/usr/bin/env bash", "set -euo pipefail", "",
                 f"# Generated by Initra for {manager}", "# Review before running.", ""]
        if packages:
            if manager == "dnf":
                lines += ["sudo dnf makecache", f"sudo dnf install -y {quoted}", ""]
            elif manager == "pacman":
                lines += [f"sudo pacman -S --needed --noconfirm {quoted}", ""]
            elif manager == "zypper":
                lines += ["sudo zypper --non-interactive refresh",
                          f"sudo zypper --non-interactive install {quoted}", ""]
            else:
                lines += ["sudo apt-get update", f"sudo apt-get install -y {quoted}", ""]
        for service in sorted(set(profile.get("services", []))):
            lines += [f"sudo systemctl enable --now {shlex.quote(service)}", ""]
        lines += ['echo "Initra setup script finished."', ""]
        return "\n".join(lines)

    @classmethod
    def export_shell(cls, profile, destination):
        path = Path(destination)
        path.write_text(cls.shell_script(profile), encoding="utf-8")
        try:
            path.chmod(path.stat().st_mode | 0o111)
        except OSError:
            pass
        return path
